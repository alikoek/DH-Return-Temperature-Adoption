def table_nested_logit():
    df = pd.read_csv(PAPER / 'nested_logit' / 'nl_robustness.csv')
    df = df[df['year'] == 2030]

    partition_labels = {'A': 'Choice structure', 'B': 'Component family'}
    rows = []
    for pname in ('A', 'B'):
        for theta in (1.0, 0.7, 0.5, 0.3):
            sub = df[(df['partition'] == pname) & (df['theta'] == theta)]
            top = sub.sort_values('rank').head(3)
            top_str = ', '.join(
                ROW_LABELS[m].split(' ')[0] if m != 'baseline' else 'DN'
                for m in top['measure_id'])
            dn = float(sub.loc[sub['measure_id'] == 'baseline',
                               'stock_weighted_share'].iloc[0]) * 100
            mx = float(sub['delta_pp'].abs().max())
            label = ('MNL ($\\theta=1$)' if theta == 1.0 else f"$\\theta={theta}$")
            cell = partition_labels[pname] if theta == 1.0 else ''
            rows.append(f"{cell} & {label} & {top_str} & {dn:.1f} & {mx:.1f} \\\\")

    content = (
        "% Generated by make_tables.py\n"
        "% src: outputs/paper_analysis/nested_logit/nl_robustness.csv\n"
        "\\begin{table}[htbp]\n\\centering\n"
        "\\caption{Nested-logit robustness check (reference scenario, 2030). The choice-structure "
        "partition nests do-nothing / single measures / combinations, and the component-family "
        "partition nests by "
        "dominant component family. Lower $\\theta$ means stronger within-nest substitution. "
        "$\\theta=1$ reproduces the multinomial logit. The last column reports the largest "
        "absolute change of any alternative's stock-weighted share relative to the MNL.}\n"
        "\\label{tab:nl}\n"
        "\\small\n"
        "\\begin{tabular}{lllcc}\n\\toprule\n"
        "Partition & Model & Top-3 alternatives & Do-nothing (\\%) & max $|\\Delta|$ (pp) \\\\\n"
        "\\midrule\n" + "\n".join(rows) + "\n"
        "\\bottomrule\n\\end{tabular}\n\\end{table}\n")
    write(OUT / 'table_nested_logit.tex', content)


