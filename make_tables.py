def table_archetypes():
    all_measures = load_all_measures()
    first = next(iter(all_measures.values()))
    reno = load_renovation_data(year=2030, archetype_types=first['building_types'])
    baseline_rts = load_building_baseline_rt()

    rows = []
    for bt in ARCHETYPE_ORDER:
        cls = reno['building_classes'][bt]
        no_action = next(v for v in cls['variants'] if v['action'] == 'no action')
        stock = sum(v['number_of_buildings'] for v in cls['variants'])
        period, size = bt.split('_')
        dwellings = size.replace('TOP', '').strip()
        rt = baseline_rts.get(bt, float('nan'))
        rows.append(
            f"{esc(display_name(bt))} & {'pre-1919' if period == '1919' else period} & {dwellings} & "
            f"{no_action['hwb_norm']:.0f} & {no_action['fed_sh_per_bssh'] / 1000.0:.1f} & "
            f"{stock:.0f} & {rt:.1f} \\\\")

    content = (
        "% Generated by make_tables.py\n"
        "% src: data/building_measures.xlsx + data/invert_building_stock_2030.csv\n"
        "\\begin{table}[htbp]\n\\centering\n"
        "\\caption{Building archetypes of the Austrian multi-family case study. "
        "The specific space-heating demand $\\qsh$ and the final energy demand (FED) refer to the "
        "unrenovated (no-action) state in the 2030 "
        "building-stock scenario. The weight is the number of buildings in the modeled Invert building "
        "stock, summed across all renovation states, and sets the relative importance of each archetype in "
        "the aggregation. The baseline return temperature $\\Trtb$ is the annual mean from the building simulations.}\n"
        "\\label{tab:archetypes}\n"
        "\\footnotesize\n"
        "\\setlength{\\tabcolsep}{3.5pt}\n"
        "\\begin{tabular}{llccccc}\n\\toprule\n"
        "Archetype & Period & Dwellings & $\\qsh$ & FED & Weight & $\\Trtb$ \\\\\n"
        " & & & (kWh\\,m$^{-2}$\\,a$^{-1}$) & (MWh\\,a$^{-1}$) & (buildings) & ($^{\\circ}$C) \\\\\n"
        "\\midrule\n" + "\n".join(rows) + "\n"
        "\\bottomrule\n\\end{tabular}\n\\end{table}\n")
    write(OUT / 'table_archetypes.tex', content)


