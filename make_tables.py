def esc(s):
    return str(s).replace('_', '\\_').replace('%', '\\%').replace('&', '\\&')


def display_name(bt):
    """Normalize raw archetype keys for display ('1960_TOP12' -> '1960_TOP 12')."""
    return bt.replace('TOP12', 'TOP 12')


def fmt_range(arr, decimals=1, thousands=False):
    lo, hi = float(np.min(arr)), float(np.max(arr))
    def f(x):
        if thousands:
            return f"{x:,.0f}"
        return f"{x:.{decimals}f}"
    if abs(hi - lo) < 10 ** (-decimals) / 2:
        return f"${f(lo)}$" if lo < 0 else f(lo)
    if lo < 0:
        # math-mode minus signs; '--' after a minus would render as an em dash
        return f"${f(lo)}$ to ${f(hi)}$"
    return f"{f(lo)}--{f(hi)}"


def write(path, content):
    path.write_text(content, encoding='utf-8')
    print(f"[OK] {path}")


