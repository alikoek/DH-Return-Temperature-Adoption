def money(x):
    sign = '$-$' if x < 0 else '+'
    return f"{sign}{abs(x):,.0f}"


def table_main_results():
    df = pd.read_csv(PAPER / 'base_case' / 'overall_shares_with_diffusion.csv')
    nv = pd.read_csv(PAPER / 'base_case' / 'network_value_2030.csv',
                     dtype={'measure_id': str}).set_index('measure_id')
    piv_choice = df.pivot(index='measure_id', columns='year', values='choice_share')
    piv_stock = df.pivot(index='measure_id', columns='year', values='stock_adoption')

    rows = []
    for mid in ALL_IDS:
        if mid == 'baseline':
            tail = "0.0 & --- & ---"
        else:
            d_rt = nv.loc[mid, 'd_rt_K']
            lo, hi = nv.loc[mid, 'v_net_mid_EUR'], nv.loc[mid, 'v_net_high_EUR']
            if abs(hi) < 1.0:
                val = "$<$1"
            elif lo < 0:
                val = f"$-${abs(lo):.0f} to $-${abs(hi):.0f}"
            else:
                val = f"{lo:.0f}--{hi:.0f}"
            d_rt_s = f"{d_rt:.1f}".replace('-', '$-$')
            tail = f"{d_rt_s} & {val} & {money(nv.loc[mid, 'net_cost_change_EUR'])}"
        rows.append(
            f"{ROW_LABELS[mid]} & "
            f"{piv_choice.loc[mid, 2030] * 100:.1f} & {piv_choice.loc[mid, 2040] * 100:.1f} & "
            f"{piv_stock.loc[mid, 2030] * 100:.1f} & {piv_stock.loc[mid, 2040] * 100:.1f} & "
            f"{tail} \\\\")

    content = (
        "% Generated by make_tables.py\n"
        "% src: outputs/paper_analysis/base_case/overall_shares_with_diffusion.csv,\n"
        "%      outputs/paper_analysis/base_case/network_value_2030.csv\n"
        "\\begin{table*}[htbp]\n\\centering\n"
        "\\caption{Stock-weighted results for the reference scenario (no tariff, no subsidy, "
        "$\\lambda=4$, 0.10\\,EUR\\,kWh$^{-1}$). Choice shares are conditional on a decision "
        "occasion. Stock adoption applies $d_{2030}=20\\,\\%$ and $d_{2040}=60\\,\\%$ and counts "
        "the remaining stock as do-nothing. Last three columns (2030, per building): "
        "$\\Delta T_{\\mathrm{RT}}$, network value at gradients of 0.12 and "
        "0.67\\,EUR\\,MWh$^{-1}$\\,K$^{-1}$ (Eq.~3), and change in the owner's total annual "
        "heating cost relative to do-nothing (Eq.~1).}\n"
        "\\label{tab:mainresults}\n"
        "\\footnotesize\n"
        "\\setlength{\\tabcolsep}{4pt}\n"
        "\\begin{tabular}{lcccccrr}\n\\toprule\n"
        " & \\multicolumn{2}{c}{Choice share (\\%)} & \\multicolumn{2}{c}{Stock adoption (\\%)} "
        "& $\\Delta T_{\\mathrm{RT}}$ & Network value & Owner cost change \\\\\n"
        "\\cmidrule(lr){2-3}\\cmidrule(lr){4-5}\n"
        "Alternative & 2030 & 2040 & 2030 & 2040 & (K) & (EUR\\,a$^{-1}$) & (EUR\\,a$^{-1}$) \\\\\n"
        "\\midrule\n" + "\n".join(rows) + "\n"
        "\\bottomrule\n\\end{tabular}\n\\end{table*}\n")
    write(OUT / 'table_main_results.tex', content)


